import mongoose from 'mongoose';
import fs from 'node:fs';
import path from 'node:path';
import { verifyMagicBytes, checksumOf, resolveKey, STORAGE_ROOT } from '../../src/services/documents/storage.js';
import {
  ENTITY_MODEL, ENTITY_VIEW_PERMISSION, DOCUMENT_ENTITIES,
  ALLOWED_TYPES, ALLOWED_MIME_TYPES, INLINE_SAFE_TYPES, MAX_FILE_BYTES,
} from '../../src/constants/documents.js';
import { ALL_PERMISSION_CODES } from '../../src/constants/permissions.js';

/** Builds a buffer with the given hex prefix, padded so it has some length. */
const withMagic = (hex) => Buffer.concat([Buffer.from(hex, 'hex'), Buffer.alloc(64)]);

describe('file type verification', () => {
  it('accepts a file whose bytes match its declared type', () => {
    expect(verifyMagicBytes(withMagic('25504446'), 'application/pdf')).toBe(true);
    expect(verifyMagicBytes(withMagic('89504e470d0a1a0a'), 'image/png')).toBe(true);
    expect(verifyMagicBytes(withMagic('ffd8ffe0'), 'image/jpeg')).toBe(true);
  });

  it('rejects an executable dressed as an image', () => {
    // 4d5a is "MZ" — a Windows executable. The browser would have told us
    // image/png quite happily, because the client supplies that header.
    expect(() => verifyMagicBytes(withMagic('4d5a9000'), 'image/png'))
      .toThrow(/does not look like a PNG/);
  });

  it('rejects a PDF that is really a ZIP', () => {
    expect(() => verifyMagicBytes(withMagic('504b0304'), 'application/pdf'))
      .toThrow(/does not look like a PDF/);
  });

  it('rejects an HTML payload claiming to be a PNG', () => {
    const html = Buffer.from('<script>fetch("/api/v1/users")</script>');
    expect(() => verifyMagicBytes(html, 'image/png')).toThrow(/does not look like/);
  });

  it('refuses a type that is not on the allowlist at all', () => {
    expect(() => verifyMagicBytes(withMagic('25504446'), 'image/svg+xml'))
      .toThrow(/not accepted/);
    expect(() => verifyMagicBytes(withMagic('25504446'), 'text/html'))
      .toThrow(/not accepted/);
    expect(() => verifyMagicBytes(withMagic('25504446'), 'application/x-msdownload'))
      .toThrow(/not accepted/);
  });

  it('lets signature-free text types through on the allowlist alone', () => {
    // A CSV genuinely has no magic number. Safety for these rests on the
    // allowlist and the attachment download headers, not on the bytes.
    expect(verifyMagicBytes(Buffer.from('a,b,c\n1,2,3'), 'text/csv')).toBe(true);
    expect(ALLOWED_TYPES['text/csv'].magic).toBeNull();
  });

  it('keeps the dangerous renderable formats off the allowlist', () => {
    // SVG is XML that browsers execute. An image format that runs code is not
    // an image. HTML needs no explanation. ZIP cannot be inspected without
    // unpacking it, which is its own vulnerability class.
    for (const forbidden of ['image/svg+xml', 'text/html', 'application/zip', 'application/xml']) {
      expect(ALLOWED_MIME_TYPES).not.toContain(forbidden);
    }
  });

  it('only ever renders inline what is safe to render', () => {
    for (const type of INLINE_SAFE_TYPES) {
      expect(ALLOWED_MIME_TYPES).toContain(type);
    }
    // Office documents and text download rather than render.
    expect(INLINE_SAFE_TYPES).not.toContain('text/csv');
    expect(INLINE_SAFE_TYPES).not.toContain('text/plain');
    expect(INLINE_SAFE_TYPES.some((t) => t.includes('officedocument'))).toBe(false);
  });
});

describe('storage key resolution', () => {
  it('resolves a normal key inside the storage root', () => {
    const resolved = resolveKey(path.join('tenant1', 'ab', 'abcdef.pdf'));
    expect(resolved.startsWith(STORAGE_ROOT)).toBe(true);
  });

  it('refuses a key that climbs out of the storage root', () => {
    // Belt and braces: keys are generated by us and should never look like
    // this. The check exists for the corrupted record and the careless future
    // code path.
    for (const escape of [
      '../../../etc/passwd',
      'tenant1/../../../../etc/shadow',
      '/etc/passwd',
      'tenant1/./../../outside.txt',
    ]) {
      expect(() => resolveKey(escape)).toThrow(/Invalid document reference/);
    }
  });

  it('refuses a key that only looks like a sibling of the root', () => {
    // "/storage/documents-evil" starts with "/storage/documents" as a string
    // but is a different directory. The separator check is what catches it.
    expect(() => resolveKey('../documents-evil/file.pdf')).toThrow();
  });

  it('does not write the uploader filename into the path', () => {
    // The storage module never receives the original name. Proven by reading
    // the source: a future edit that threads it through fails here.
    const source = fs.readFileSync(
      new URL('../../src/services/documents/storage.js', import.meta.url),
      'utf8',
    );
    expect(source).not.toMatch(/originalname/i);
    expect(source).not.toMatch(/originalName/);
  });
});

describe('checksums', () => {
  it('is stable for the same bytes and different for different bytes', () => {
    const a = Buffer.from('invoice contents');
    expect(checksumOf(a)).toBe(checksumOf(Buffer.from('invoice contents')));
    expect(checksumOf(a)).not.toBe(checksumOf(Buffer.from('invoice contents ')));
  });

  it('is a full SHA-256', () => {
    expect(checksumOf(Buffer.from('x'))).toMatch(/^[0-9a-f]{64}$/);
  });
});

describe('entity wiring', () => {
  beforeAll(async () => {
    for (const file of fs.readdirSync(new URL('../../src/models', import.meta.url))) {
      await import(`../../src/models/${file}`);
    }
  });

  it('maps every entity type to a model that actually exists', () => {
    // This caught a real mistake during Phase 10: the transfer entity pointed
    // at 'StockTransfer', and the model is called 'WarehouseTransfer'. The
    // failure would have been a 500 on upload, discovered by a user.
    const registered = new Set(mongoose.modelNames());

    for (const entity of DOCUMENT_ENTITIES) {
      expect([entity, registered.has(ENTITY_MODEL[entity])]).toEqual([entity, true]);
    }
  });

  it('gives every entity type a view permission that exists', () => {
    const known = new Set(ALL_PERMISSION_CODES);

    for (const entity of DOCUMENT_ENTITIES) {
      const permission = ENTITY_VIEW_PERMISSION[entity];
      expect([entity, permission, known.has(permission)]).toEqual([entity, permission, true]);
    }
  });

  it('leaves no entity type unmapped', () => {
    // A missing entry would mean a document attached with no parent permission
    // check — the exact hole the mapping exists to close.
    expect(Object.keys(ENTITY_MODEL).sort()).toEqual([...DOCUMENT_ENTITIES].sort());
    expect(Object.keys(ENTITY_VIEW_PERMISSION).sort()).toEqual([...DOCUMENT_ENTITIES].sort());
  });
});

describe('limits', () => {
  it('bounds the file size somewhere sane', () => {
    expect(MAX_FILE_BYTES).toBeGreaterThan(1024 * 1024);
    expect(MAX_FILE_BYTES).toBeLessThanOrEqual(25 * 1024 * 1024);
  });

  it('gives every allowed type exactly one canonical extension', () => {
    for (const [mime, spec] of Object.entries(ALLOWED_TYPES)) {
      expect([mime, spec.ext.startsWith('.')]).toEqual([mime, true]);
      // The extension comes from here, never from the uploaded filename.
      expect([mime, spec.ext]).toEqual([mime, spec.ext.toLowerCase()]);
    }
  });
});
