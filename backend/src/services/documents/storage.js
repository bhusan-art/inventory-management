import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import env from '../../config/env.js';
import { ALLOWED_TYPES } from '../../constants/documents.js';
import { DomainError } from '../../utils/errors.js';

/**
 * Where files live on disk, and the rules about getting them there.
 *
 * The storage root is configuration, never request data. Everything below
 * builds paths from values WE chose — a tenant id from the authenticated
 * actor, a random name, an extension from the verified MIME type — so there is
 * no concatenation of user input into a path anywhere in this file. That is
 * the point: path traversal is not validated against, it is unreachable.
 */
const STORAGE_ROOT = path.resolve(env.DOCUMENT_STORAGE_PATH);

/** 32 random bytes, hex. Unguessable, so a stored file cannot be found by trying names. */
function randomName() {
  return crypto.randomBytes(32).toString('hex');
}

/**
 * Confirms the bytes are what the Content-Type claimed.
 *
 * The browser's declared type is supplied by whoever is uploading, so it is a
 * hint and not evidence. A .exe announced as image/png is caught here, by
 * reading the actual leading bytes.
 *
 * Some accepted types genuinely have no signature — a CSV is just text — and
 * for those the extension allowlist plus the download headers are what carry
 * the safety, not the magic number.
 */
export function verifyMagicBytes(buffer, mimeType) {
  const spec = ALLOWED_TYPES[mimeType];
  if (!spec) {
    throw new DomainError(`${mimeType} files are not accepted`, 'FILE_TYPE_NOT_ALLOWED');
  }
  if (!spec.magic) return true;

  const head = buffer.subarray(0, 16).toString('hex');
  const matches = spec.magic.some((signature) => head.startsWith(signature));

  if (!matches) {
    throw new DomainError(
      `This file does not look like a ${mimeType.split('/').pop().toUpperCase()}. `
      + 'Its contents do not match the type it claims to be.',
      'FILE_CONTENT_MISMATCH',
    );
  }
  return true;
}

export function checksumOf(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

/**
 * Writes the file and returns its storage key.
 *
 * Sharded by tenant and by the first two characters of the random name. The
 * tenant directory keeps one customer's files out of another's even at the
 * filesystem level; the two-character fan-out stops a single directory
 * accumulating a million entries, which some filesystems handle badly.
 */
export async function store(buffer, { tenantId, mimeType }) {
  const name = randomName();
  const { ext } = ALLOWED_TYPES[mimeType];

  // Every component is ours: an ObjectId, hex characters, and a fixed
  // extension from the allowlist. No request data reaches this path.
  const key = path.join(String(tenantId), name.slice(0, 2), `${name}${ext}`);
  const absolute = path.join(STORAGE_ROOT, key);

  await fs.mkdir(path.dirname(absolute), { recursive: true });
  // 'wx' fails rather than overwriting, so a name collision can never destroy
  // an existing document.
  await fs.writeFile(absolute, buffer, { flag: 'wx', mode: 0o640 });

  return key;
}

/**
 * Resolves a storage key to an absolute path, refusing anything that escapes
 * the storage root.
 *
 * Keys are generated by `store` and should always be safe. This check exists
 * for the case where one is not — a corrupted record, a bad migration, a
 * future code path that builds a key carelessly. Defence in depth costs two
 * lines here and removes a whole class of outcome.
 */
export function resolveKey(key) {
  const absolute = path.resolve(STORAGE_ROOT, key);
  const root = STORAGE_ROOT.endsWith(path.sep) ? STORAGE_ROOT : STORAGE_ROOT + path.sep;

  if (!absolute.startsWith(root)) {
    throw new DomainError('Invalid document reference', 'INVALID_STORAGE_KEY');
  }
  return absolute;
}

export async function read(key) {
  return fs.readFile(resolveKey(key));
}

export async function remove(key) {
  await fs.unlink(resolveKey(key)).catch(() => {});
}

export async function exists(key) {
  return fs.access(resolveKey(key)).then(() => true).catch(() => false);
}

export { STORAGE_ROOT };
